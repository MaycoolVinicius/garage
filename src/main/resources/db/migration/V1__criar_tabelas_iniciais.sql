CREATE TABLE cliente (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    telefone  VARCHAR(20)  NOT NULL
);

CREATE TABLE ordem_servico (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     BIGINT         NOT NULL REFERENCES cliente (id),
    placa          VARCHAR(10)    NOT NULL,
    data_abertura  TIMESTAMP(6)   NOT NULL,
    valor_total    NUMERIC(12, 2) NOT NULL
);

CREATE TABLE item_servico (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id  BIGINT         NOT NULL REFERENCES ordem_servico (id),
    tipo              VARCHAR(10)    NOT NULL,
    descricao         VARCHAR(200)   NOT NULL,
    quantidade        INTEGER        NOT NULL,
    valor_unitario    NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_cliente_telefone ON cliente (telefone);
CREATE INDEX idx_os_cliente ON ordem_servico (cliente_id);
CREATE INDEX idx_os_placa ON ordem_servico (placa);
CREATE INDEX idx_os_data_abertura ON ordem_servico (data_abertura DESC);
CREATE INDEX idx_item_os ON item_servico (ordem_servico_id);